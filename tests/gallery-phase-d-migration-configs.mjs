async function withFixture(callback) {
    const root = await fs.mkdtemp(path.join(os.tmpdir(), 'gallery-phase-d-migration-'));
    assert.equal(path.dirname(root), os.tmpdir());
    try {
        await fs.mkdir(path.join(root, 'gallery-admin', 'migrations'), { recursive: true });
        await fs.writeFile(
            path.join(root, 'gallery-admin', '.gitignore'),
            '.wrangler/\nwrangler.admin.local.jsonc\n'
        );
        for (const [index, migrationName] of migrationNames.entries()) {
            await fs.writeFile(
                path.join(root, 'gallery-admin', 'migrations', migrationName),
                `-- synthetic ${migrationName}\nSELECT ${index + 1};\n`
            );
        }
        await callback(root);
    } finally {
        assert.equal(path.dirname(root), os.tmpdir());
        await fs.rm(root, { recursive: true, force: true });
    }
}

async function writeAdminConfig(root, config, { jsonc = false } = {}) {
    let text = JSON.stringify(config, null, 2);
    if (jsonc) {
        text = `// Synthetic populated admin config.\n${text.replace(/\n}$/, ',\n}')}`;
    }
    await fs.writeFile(
        path.join(root, 'gallery-admin', 'wrangler.admin.local.jsonc'),
        `${text}\n`
    );
}

function runWrangler(cwd, args) {
    return spawnSync(process.execPath, [wranglerPath, ...args], {
        cwd,
        encoding: 'utf8',
        env: {
            ...process.env,
            CI: '1',
            WRANGLER_SEND_METRICS: 'false'
        },
        timeout: 30_000
    });
}

function allOutput(result) {
    return `${result.stdout || ''}\n${result.stderr || ''}`;
}

function diagnostic(result) {
    return `Wrangler exited ${result.status}: ${allOutput(result)}`;
}

async function exists(target) {
    try {
        await fs.access(target);
        return true;
    } catch {
        return false;
    }
}
