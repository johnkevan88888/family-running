async function withFixture(callback) {
    const root = await fs.mkdtemp(path.join(os.tmpdir(), 'gallery-phase-d-processing-'));
    assert.equal(path.dirname(root), os.tmpdir());
    try {
        await fs.mkdir(path.join(root, 'gallery-admin'), { recursive: true });
        await fs.writeFile(
            path.join(root, 'gallery-admin', '.gitignore'),
            '.wrangler/\nwrangler.admin.local.jsonc\n'
        );
        await fs.cp(
            path.join(repositoryRoot, 'gallery-admin', 'src'),
            path.join(root, 'gallery-admin', 'src'),
            { recursive: true }
        );
        await fs.cp(
            path.join(repositoryRoot, 'gallery-admin', 'generated'),
            path.join(root, 'gallery-admin', 'generated'),
            { recursive: true }
        );
        await fs.mkdir(path.join(root, 'scripts'), { recursive: true });
        await fs.copyFile(
            path.join(repositoryRoot, 'scripts', 'gallery-media-toolchain.json'),
            path.join(root, 'scripts', 'gallery-media-toolchain.json')
        );
        for (const contract of ['gallery-contract.js', 'gallery-upload-contract.js']) {
            await fs.copyFile(
                path.join(repositoryRoot, contract),
                path.join(root, contract)
            );
        }
        await callback(root);
    } finally {
        assert.equal(path.dirname(root), os.tmpdir());
        await fs.rm(root, { recursive: true, force: true });
    }
}

async function writeAdminConfig(root, config) {
    await fs.writeFile(
        path.join(root, 'gallery-admin', 'wrangler.admin.local.jsonc'),
        `${JSON.stringify(config, null, 2)}\n`
    );
}

function runWrangler(cwd, args) {
    return spawnSync(process.execPath, [wranglerPath, ...args], {
        cwd,
        encoding: 'utf8',
        env: {
            ...process.env,
            CI: '1',
            WRANGLER_SEND_METRICS: 'false'
        },
        timeout: 30_000
    });
}

function allOutput(result) {
    return `${result.stdout || ''}\n${result.stderr || ''}`;
}

function diagnostic(result) {
    return `Wrangler exited ${result.status}: ${allOutput(result)}`;
}

async function exists(target) {
    try {
        await fs.access(target);
        return true;
    } catch {
        return false;
    }
}

async function readJavaScriptOutput(directory) {
    const entries = await fs.readdir(directory, { withFileTypes: true });
    const files = entries
        .filter(entry => entry.isFile() && entry.name.endsWith('.js'))
        .map(entry => path.join(directory, entry.name));
    assert.ok(files.length >= 1, 'Wrangler dry-run must emit JavaScript.');
    return (await Promise.all(files.map(file => fs.readFile(file, 'utf8')))).join('\n');
}
