// Audits the declared tier table against what the checks actually read.
//
// On demand, not in the suite: it runs every registered check once with an `fs`
// hook recording the repository files it opens, which costs about as long as a
// full suite run. The result is written to
// `tests/fixtures/check-read-surfaces.json` and committed, so
// `tests/change-tier.mjs` can enforce the audit at suite speed without tracing
// anything.
//
// The audit is deliberately one-directional. A check that reads a tier's files
// and is NOT in that tier is a hole, and that fails. The reverse -- a check in
// a tier that never opened one of its files -- is not a fault: a check can be
// responsible for a path it does not read, by asserting the file is absent or
// by asserting on output built from it. Tracing cannot see responsibility, only
// reads, which is exactly why it audits the reviewed table instead of
// replacing it.
//
// Run after changing a tier, adding a check, or changing what a check reads:
//     node scripts/trace-check-reads.mjs

import { spawn } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { environmentFor } from './check-lanes.mjs';
import { readRegisteredCheckCommands } from './classify-change-tier.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const hook = path.join(repoRoot, 'scripts', 'check-read-hook.cjs');
const output = path.join(repoRoot, 'tests', 'fixtures', 'check-read-surfaces.json');
const allCommands = readRegisteredCheckCommands(repoRoot);
const allChecks = allCommands.map(command => command.script);
const commandFor = new Map(allCommands.map(command => [command.script, command.args]));
// `--only=a.mjs,b.mjs` re-traces just those checks and merges them into the
// existing record, so one changed check does not cost a whole suite again.
const onlyFlag = process.argv.find(argument => argument.startsWith('--only='));
const only = onlyFlag ? onlyFlag.slice('--only='.length).split(',').filter(Boolean) : null;
const checks = only ? allChecks.filter(check => only.includes(check)) : allChecks;

if (only && checks.length !== only.length) {
    console.error(`--only named ${only.length} checks but ${checks.length} are registered; refusing rather than tracing a partial list.`);
    process.exit(1);
}
const scratch = mkdtempSync(path.join(os.tmpdir(), 'family-running-trace-'));
/**
 * Only the paths a tier can be declared over.
 *
 * A full trace is 6324 paths and 371 KB, four fifths of it module resolution:
 * every check "reads" the `scripts/` and `tests/` files it imports, and no tier
 * is declared over those because any change there runs everything anyway.
 * Keeping the surfaces a tier could plausibly cover -- exported data, editorial
 * metadata, brand assets, vendored libraries and the published root files --
 * leaves 1298 paths and 62 KB, with nothing the audit uses removed.
 */
function tierRelevant(file) {
    return /^(?:data|gallery-data|assets|vendor)\//.test(file) ||
        /^[^/]+\.(?:html|css|js|json|txt)$/.test(file) ||
        file === 'CNAME';
}

let surfaces = {};

if (only) {
    try {
        surfaces = JSON.parse(readFileSync(output, 'utf8')).surfaces || {};
    } catch {
        console.error('--only needs an existing record to merge into; run the full trace first.');
        process.exit(1);
    }
}
const failures = [];
const started = Date.now();

console.log(`Tracing ${checks.length} checks. This runs the whole suite under an fs hook, so expect it to take about as long.`);

try {
    for (const [index, check] of checks.entries()) {
        const tracePath = path.join(scratch, `${index}.txt`);
        const code = await run(check, tracePath);
        let reads = [];

        try {
            reads = [...new Set(readFileSync(tracePath, 'utf8').split('\n').filter(Boolean))]
                .filter(tierRelevant)
                .sort();
        } catch {
            reads = [];
        }

        surfaces[check] = reads;

        if (code !== 0) {
            failures.push({ check, code });
        }

        console.log(`[${index + 1}/${checks.length}] ${check} — ${reads.length} files, exit ${code}`);
    }
} finally {
    rmSync(scratch, { recursive: true, force: true });
}

writeFileSync(output, `${JSON.stringify({
    note: 'Generated by scripts/trace-check-reads.mjs. Audit instrumentation: nothing depends on it at runtime. Repository paths each check opened, with artifact reads mapped back to their source path.',
    tracedAt: new Date().toISOString().slice(0, 10),
    platform: process.platform,
    nodeMajor: Number(process.versions.node.split('.')[0]),
    surfaces
}, null, 2)}\n`);

const total = Object.values(surfaces).reduce((sum, reads) => sum + reads.length, 0);

console.log(`\nRecorded ${Object.keys(surfaces).length} checks and ${total} read paths to ` +
    `${path.relative(repoRoot, output)} in ${((Date.now() - started) / 1000).toFixed(0)}s.`);

if (failures.length > 0) {
    // A failing check still produces a usable read set, but the trace is only
    // trustworthy for a check that ran to completion -- one that aborted early
    // may not have opened everything it normally would.
    console.error(`\n${failures.length} check(s) did not pass while traced, so their read sets may be incomplete:`);
    for (const failure of failures) {
        console.error(`- ${failure.check} (exit ${failure.code})`);
    }
    process.exit(1);
}

console.log('Every traced check passed, so each read set is complete.');

function run(check, tracePath) {
    return new Promise(resolve => {
        const existing = process.env.NODE_OPTIONS ? `${process.env.NODE_OPTIONS} ` : '';
        const child = spawn(process.execPath, commandFor.get(check) || [check], {
            cwd: repoRoot,
            env: {
                ...process.env,
                ...environmentFor(check),
                NODE_OPTIONS: `${existing}--require ${JSON.stringify(hook)}`,
                FAMILY_RUNNING_TRACE: tracePath,
                FAMILY_RUNNING_TRACE_ROOT: repoRoot
            },
            stdio: 'ignore',
            windowsHide: true
        });

        child.on('error', () => resolve(-1));
        child.on('close', code => resolve(code ?? 1));
    });
}
