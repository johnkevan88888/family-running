import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { parseCsv, repoRoot } from './export-bundle-tools.mjs';

const snapshotSchemaVersion = '1.0';
const siteModes = Object.freeze(['family', 'everyone']);
const outputRelativePath = 'gallery-admin/generated/catalog-snapshot.js';
const manifestRelativePath = 'data/export_manifest.csv';
const athleteResultsRelativePath = 'data/athlete_results.csv';
const suppressionRelativePath = 'gallery-data/hidden-athlete-ids.json';
const sourceRelativePaths = Object.freeze([
    manifestRelativePath,
    athleteResultsRelativePath,
    ...siteModes.map(mode => `data/${mode}/age_grade_standards.csv`)
]);
const manifestHeaders = Object.freeze([
    'ExportBundleID',
    'ExportedAtUTC',
    'SchemaVersion',
    'Scope',
    'RelativePath',
    'DataRowCount'
]);
const athleteResultHeaders = Object.freeze([
    'AthleteID',
    'Participant',
    'Date',
    'Distance',
    'Time',
    'AgeGrade',
    'Event',
    'TimeClass',
    'ExportBundleID'
]);
const ageGradeStandardHeaders = Object.freeze([
    'AthleteId',
    'Distance',
    'Standard',
    'AgeGrade',
    'RequiredTime',
    'pace_per_km',
    'pace_per_mile',
    'SortOrder',
    'ExportBundleID'
]);
const athleteIdPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const exportBundleIdPattern = /^[A-Za-z0-9][A-Za-z0-9_-]{0,199}$/;

export async function buildGalleryAdminCatalog(root = repoRoot) {
    const sourceTexts = new Map();

    for (const relativePath of sourceRelativePaths) {
        sourceTexts.set(relativePath, await readPublicText(root, relativePath));
    }

    const suppressionText = await readPublicText(root, suppressionRelativePath);
    const manifest = parseExactCsv(
        sourceTexts.get(manifestRelativePath),
        manifestRelativePath,
        manifestHeaders
    );
    const manifestContract = validateManifest(manifest);
    const athleteResultsCsv = parseExactCsv(
        sourceTexts.get(athleteResultsRelativePath),
        athleteResultsRelativePath,
        athleteResultHeaders
    );
    validateManifestInput(
        manifestContract,
        athleteResultsRelativePath,
        'shared',
        athleteResultsCsv.rows.length
    );

    const athleteResults = buildAthleteResults(
        athleteResultsCsv,
        manifestContract.exportBundleId
    );
    const sourceRevision = revisionForEntries(
        'family-running-gallery-admin-catalog-source-v1',
        sourceRelativePaths.map(relativePath => ({
            relativePath,
            text: sourceTexts.get(relativePath)
        }))
    );
    const suppressionDocument = parseSuppressionDocument(suppressionText);
    const suppressionRevision = revisionForEntries(
        'family-running-gallery-admin-suppression-v1',
        [{ relativePath: suppressionRelativePath, text: suppressionText }]
    );
    const sites = {};

    for (const mode of siteModes) {
        const relativePath = `data/${mode}/age_grade_standards.csv`;
        const standardsCsv = parseExactCsv(
            sourceTexts.get(relativePath),
            relativePath,
            ageGradeStandardHeaders
        );
        validateManifestInput(
            manifestContract,
            relativePath,
            mode,
            standardsCsv.rows.length
        );
        const rosterIds = buildSiteRosterIds(
            standardsCsv,
            relativePath,
            manifestContract.exportBundleId
        );

        sites[mode] = buildSiteSnapshot({
            mode,
            rosterIds,
            athleteResults,
            exportBundleId: manifestContract.exportBundleId,
            sourceRevision
        });
    }

    return {
        schemaVersion: snapshotSchemaVersion,
        exportBundleId: manifestContract.exportBundleId,
        sourceRevision,
        suppressionRevision,
        suppressionDocument,
        sites
    };
}

export function renderGalleryAdminCatalog(snapshot) {
    const serialized = JSON.stringify(snapshot, null, 4)
        .replace(/\u2028/g, '\\u2028')
        .replace(/\u2029/g, '\\u2029');

    return `// Generated by scripts/build-gallery-admin-catalog.mjs. Do not edit by hand.\n` +
        `const snapshot = ${serialized};\n\n` +
        `function deepFreeze(value) {\n` +
        `    if (value && typeof value === 'object' && !Object.isFrozen(value)) {\n` +
        `        Object.freeze(value);\n` +
        `        for (const child of Object.values(value)) {\n` +
        `            deepFreeze(child);\n` +
        `        }\n` +
        `    }\n` +
        `    return value;\n` +
        `}\n\n` +
        `export const galleryAdminCatalogSnapshot = deepFreeze(snapshot);\n` +
        `export default galleryAdminCatalogSnapshot;\n`;
}

export async function writeGalleryAdminCatalog(options = {}) {
    const root = options.root || repoRoot;
    const outputPath = path.join(root, ...outputRelativePath.split('/'));
    const snapshot = await buildGalleryAdminCatalog(root);
    const expected = renderGalleryAdminCatalog(snapshot);

    if (options.check) {
        let actual;
        try {
            actual = await fs.readFile(outputPath, 'utf8');
        } catch (error) {
            if (error?.code === 'ENOENT') {
                throw new Error(`${outputRelativePath}: generated catalog snapshot is missing.`);
            }
            throw new Error(`${outputRelativePath}: could not read the generated catalog snapshot.`);
        }

        if (actual !== expected) {
            throw new Error(
                `${outputRelativePath}: generated catalog snapshot is stale; rebuild it without --check.`
            );
        }
        return { outputPath, snapshot, changed: false };
    }

    await fs.mkdir(path.dirname(outputPath), { recursive: true });
    await fs.writeFile(outputPath, expected, 'utf8');
    return { outputPath, snapshot, changed: true };
}

export function exportedDateToIso(value, label = 'exported date') {
    const match = typeof value === 'string'
        ? value.match(/^(\d{2})\/(\d{2})\/(\d{4})$/)
        : null;

    if (!match) {
        throw new Error(`${label} must use the exact DD/MM/YYYY format.`);
    }

    const isoDate = `${match[3]}-${match[2]}-${match[1]}`;
    const parsed = new Date(`${isoDate}T00:00:00Z`);

    if (Number.isNaN(parsed.getTime()) || parsed.toISOString().slice(0, 10) !== isoDate) {
        throw new Error(`${label} must be a real calendar date.`);
    }

    return isoDate;
}

async function readPublicText(root, relativePath) {
    try {
        const text = await fs.readFile(path.join(root, ...relativePath.split('/')), 'utf8');
        return canonicalizeTextNewlines(text);
    } catch {
        throw new Error(`${relativePath}: could not read the required public source file.`);
    }
}

function parseExactCsv(text, relativePath, expectedHeaders) {
    let parsed;
    try {
        parsed = parseCsv(text);
    } catch (error) {
        throw new Error(`${relativePath}: could not parse CSV (${error.message}).`);
    }

    if (parsed.length === 0) {
        throw new Error(`${relativePath}: CSV is empty.`);
    }

    const headers = parsed[0];
    if (
        headers.length !== expectedHeaders.length ||
        headers.some((header, index) => header !== expectedHeaders[index])
    ) {
        throw new Error(
            `${relativePath}: unsupported CSV shape; expected exactly ${expectedHeaders.join(',')}.`
        );
    }

    const rows = parsed.slice(1).map((row, index) => {
        const rowNumber = index + 2;
        if (row.length !== expectedHeaders.length || row.every(value => value === '')) {
            throw new Error(`${relativePath}: row ${rowNumber} has an unsupported CSV shape.`);
        }
        return Object.fromEntries(expectedHeaders.map((header, columnIndex) => [
            header,
            String(row[columnIndex] ?? '').trim()
        ]));
    });

    return { relativePath, headers: [...headers], rows };
}

function validateManifest(manifest) {
    if (manifest.rows.length === 0) {
        throw new Error(`${manifestRelativePath}: manifest has no file entries.`);
    }

    const paths = new Map();
    let exportBundleId = null;

    manifest.rows.forEach((row, index) => {
        const rowNumber = index + 2;
        for (const header of manifestHeaders) {
            if (!row[header]) {
                throw new Error(`${manifestRelativePath}: row ${rowNumber} has a blank ${header}.`);
            }
        }
        if (!exportBundleIdPattern.test(row.ExportBundleID)) {
            throw new Error(`${manifestRelativePath}: row ${rowNumber} has an unsafe ExportBundleID.`);
        }
        if (exportBundleId === null) {
            exportBundleId = row.ExportBundleID;
        } else if (row.ExportBundleID !== exportBundleId) {
            throw new Error(`${manifestRelativePath}: all rows must use one exact ExportBundleID.`);
        }
        if (row.SchemaVersion !== snapshotSchemaVersion) {
            throw new Error(`${manifestRelativePath}: row ${rowNumber} has an unsupported SchemaVersion.`);
        }
        if (!['family', 'everyone', 'shared'].includes(row.Scope)) {
            throw new Error(`${manifestRelativePath}: row ${rowNumber} has an unsupported Scope.`);
        }
        if (!isPublicRelativeCsvPath(row.RelativePath)) {
            throw new Error(`${manifestRelativePath}: row ${rowNumber} has an unsafe RelativePath.`);
        }
        if (paths.has(row.RelativePath)) {
            throw new Error(`${manifestRelativePath}: RelativePath "${row.RelativePath}" appears more than once.`);
        }
        const dataRowCount = Number(row.DataRowCount);
        if (!/^\d+$/.test(row.DataRowCount) || !Number.isSafeInteger(dataRowCount)) {
            throw new Error(`${manifestRelativePath}: row ${rowNumber} has an invalid DataRowCount.`);
        }

        paths.set(row.RelativePath, { ...row, dataRowCount });
    });

    return { exportBundleId, paths };
}

function validateManifestInput(manifest, relativePath, expectedScope, actualRowCount) {
    const entry = manifest.paths.get(relativePath);
    if (!entry) {
        throw new Error(`${manifestRelativePath}: missing required path "${relativePath}".`);
    }
    if (entry.Scope !== expectedScope) {
        throw new Error(`${manifestRelativePath}: "${relativePath}" must use scope "${expectedScope}".`);
    }
    if (entry.ExportBundleID !== manifest.exportBundleId) {
        throw new Error(`${manifestRelativePath}: "${relativePath}" uses a different ExportBundleID.`);
    }
    if (entry.dataRowCount !== actualRowCount) {
        throw new Error(
            `${manifestRelativePath}: "${relativePath}" row count does not match its public CSV.`
        );
    }
}

function buildAthleteResults(csv, exportBundleId) {
    const namesById = new Map();
    const seenSourceResults = new Set();

    const results = csv.rows.map((row, index) => {
        const rowNumber = index + 2;
        const label = `${athleteResultsRelativePath}: row ${rowNumber}`;
        requireAthleteId(row.AthleteID, `${label} AthleteID`);
        requirePublicText(row.Participant, `${label} Participant`);
        requirePublicText(row.Event, `${label} Event`);
        requirePublicText(row.Distance, `${label} Distance`);
        requirePublicText(row.Time, `${label} Time`);
        requirePublicText(row.AgeGrade, `${label} AgeGrade`);
        if (!['Official', 'Unofficial'].includes(row.TimeClass)) {
            throw new Error(`${label} TimeClass is unsupported.`);
        }
        requireExactBundle(row.ExportBundleID, exportBundleId, label);

        const existingName = namesById.get(row.AthleteID);
        if (existingName !== undefined && existingName !== row.Participant) {
            throw new Error(`${label} assigns an inconsistent public name to athlete ID "${row.AthleteID}".`);
        }
        namesById.set(row.AthleteID, row.Participant);

        const sourceResultKey = JSON.stringify(athleteResultHeaders
            .filter(header => header !== 'ExportBundleID')
            .map(header => row[header]));
        if (seenSourceResults.has(sourceResultKey)) {
            throw new Error(`${label} duplicates an existing public result.`);
        }
        seenSourceResults.add(sourceResultKey);

        return {
            athleteId: row.AthleteID,
            participant: row.Participant,
            raceDate: exportedDateToIso(row.Date, `${label} Date`),
            raceEvent: row.Event,
            raceDistance: row.Distance
        };
    });

    if (results.length === 0) {
        throw new Error(`${athleteResultsRelativePath}: no public results are available.`);
    }

    return results;
}

function buildSiteRosterIds(csv, relativePath, exportBundleId) {
    const rosterIds = new Set();
    const seenStandards = new Set();

    csv.rows.forEach((row, index) => {
        const rowNumber = index + 2;
        const label = `${relativePath}: row ${rowNumber}`;
        requireAthleteId(row.AthleteId, `${label} AthleteId`);
        for (const field of ageGradeStandardHeaders.filter(header =>
            header !== 'AthleteId' && header !== 'ExportBundleID'
        )) {
            requirePublicText(row[field], `${label} ${field}`);
        }
        requireExactBundle(row.ExportBundleID, exportBundleId, label);

        const standardKey = JSON.stringify(ageGradeStandardHeaders
            .filter(header => header !== 'ExportBundleID')
            .map(header => row[header]));
        if (seenStandards.has(standardKey)) {
            throw new Error(`${label} duplicates an existing age-grade standard row.`);
        }
        seenStandards.add(standardKey);
        rosterIds.add(row.AthleteId);
    });

    if (rosterIds.size === 0) {
        throw new Error(`${relativePath}: no public athlete IDs are available.`);
    }

    return rosterIds;
}

function buildSiteSnapshot({ mode, rosterIds, athleteResults, exportBundleId, sourceRevision }) {
    // This is the exact result-bearing filter used by validate-gallery.mjs:
    // start with IDs from this mode's age-grade standards, then retain only
    // athletes who also have a row in the shared public results export.
    const siteResults = athleteResults.filter(result => rosterIds.has(result.athleteId));
    const participantById = new Map();

    for (const result of siteResults) {
        const existing = participantById.get(result.athleteId);
        if (existing !== undefined && existing !== result.participant) {
            throw new Error(`data/${mode}: athlete ID "${result.athleteId}" has inconsistent public names.`);
        }
        participantById.set(result.athleteId, result.participant);
    }

    const rosterEntries = [...participantById]
        .map(([athleteId, participant]) => ({ athleteId, participant }))
        .sort((left, right) =>
            comparePublicText(left.participant, right.participant) ||
            comparePublicText(left.athleteId, right.athleteId)
        );

    if (rosterEntries.length === 0) {
        throw new Error(`data/${mode}: no result-bearing public roster is available.`);
    }

    const raceByKey = new Map();
    const resultEntryByKey = new Map();
    for (const result of siteResults) {
        const race = {
            raceDate: result.raceDate,
            raceEvent: result.raceEvent,
            raceDistance: result.raceDistance
        };
        const raceKey = JSON.stringify(Object.values(race));
        raceByKey.set(raceKey, race);

        // A person can legitimately carry distinct Official and Unofficial
        // source results for the same race. The selector needs only one fact:
        // that this public athlete ID ran that exact race.
        const resultEntry = { athleteId: result.athleteId, ...race };
        const resultEntryKey = JSON.stringify(Object.values(resultEntry));
        resultEntryByKey.set(resultEntryKey, resultEntry);
    }

    const races = [...raceByKey.values()].sort(compareRaces);
    const resultEntries = [...resultEntryByKey.values()].sort((left, right) =>
        compareRaces(left, right) || comparePublicText(left.athleteId, right.athleteId)
    );
    assertUniqueByJson(races, `data/${mode}: generated race catalog`);
    assertUniqueByJson(resultEntries, `data/${mode}: generated result entries`);

    return {
        catalog: {
            exportBundleId,
            sourceRevision,
            races,
            athleteIds: rosterEntries.map(entry => entry.athleteId)
        },
        rosterEntries,
        resultEntries
    };
}

function parseSuppressionDocument(text) {
    let value;
    try {
        value = JSON.parse(text);
    } catch {
        throw new Error(`${suppressionRelativePath}: could not parse valid JSON.`);
    }

    if (!isPlainObject(value)) {
        throw new Error(`${suppressionRelativePath}: suppression document must be an object.`);
    }
    const keys = Object.keys(value);
    if (
        keys.length !== 2 ||
        !keys.includes('schemaVersion') ||
        !keys.includes('hiddenAthleteIds')
    ) {
        throw new Error(`${suppressionRelativePath}: suppression document has an unsupported shape.`);
    }
    if (value.schemaVersion !== snapshotSchemaVersion || !Array.isArray(value.hiddenAthleteIds)) {
        throw new Error(`${suppressionRelativePath}: suppression document has an unsupported contract.`);
    }

    const seen = new Set();
    value.hiddenAthleteIds.forEach((athleteId, index) => {
        requireAthleteId(
            athleteId,
            `${suppressionRelativePath}: hiddenAthleteIds[${index}]`
        );
        if (seen.has(athleteId)) {
            throw new Error(`${suppressionRelativePath}: hidden athlete ID "${athleteId}" is duplicated.`);
        }
        seen.add(athleteId);
    });

    return {
        schemaVersion: value.schemaVersion,
        hiddenAthleteIds: [...value.hiddenAthleteIds]
    };
}

function revisionForEntries(domain, entries) {
    const hash = createHash('sha256');
    hash.update(`${domain}\0`, 'utf8');

    for (const entry of [...entries].sort((left, right) =>
        comparePublicText(left.relativePath, right.relativePath)
    )) {
        // Git stores these public text sources with LF endings, while a Windows
        // checkout may present the same content with CRLF endings. Hash the
        // repository-canonical form so one committed snapshot is valid on both
        // Windows and Linux without weakening any content comparison.
        const bytes = Buffer.from(canonicalizeTextNewlines(entry.text), 'utf8');
        hash.update(`${entry.relativePath}\0${bytes.byteLength}\0`, 'utf8');
        hash.update(bytes);
        hash.update('\0', 'utf8');
    }

    return `sha256:${hash.digest('hex')}`;
}

function canonicalizeTextNewlines(text) {
    return text.replace(/\r\n?/g, '\n');
}

function requireExactBundle(value, expected, label) {
    if (value !== expected) {
        throw new Error(`${label} does not use the manifest's exact ExportBundleID.`);
    }
}

function requireAthleteId(value, label) {
    if (typeof value !== 'string' || !athleteIdPattern.test(value)) {
        throw new Error(`${label} must be a public URL-safe athlete ID.`);
    }
}

function requirePublicText(value, label) {
    if (typeof value !== 'string' || value.length === 0 || value.length > 300) {
        throw new Error(`${label} must be non-empty public text no longer than 300 characters.`);
    }
}

function isPublicRelativeCsvPath(value) {
    return typeof value === 'string' &&
        value.startsWith('data/') &&
        value.endsWith('.csv') &&
        !value.includes('\\') &&
        !value.includes('//') &&
        value.split('/').every(segment => segment && segment !== '.' && segment !== '..');
}

function isPlainObject(value) {
    if (!value || typeof value !== 'object' || Array.isArray(value)) {
        return false;
    }
    const prototype = Object.getPrototypeOf(value);
    return prototype === Object.prototype || prototype === null;
}

function comparePublicText(left, right) {
    return left < right ? -1 : left > right ? 1 : 0;
}

function compareRaces(left, right) {
    return comparePublicText(right.raceDate, left.raceDate) ||
        comparePublicText(left.raceEvent, right.raceEvent) ||
        comparePublicText(left.raceDistance, right.raceDistance);
}

function assertUniqueByJson(values, label) {
    const seen = new Set();
    for (const value of values) {
        const key = JSON.stringify(value);
        if (seen.has(key)) {
            throw new Error(`${label} contains a duplicate.`);
        }
        seen.add(key);
    }
}

async function runCli() {
    const argumentsAfterScript = process.argv.slice(2);
    if (argumentsAfterScript.some(argument => argument !== '--check')) {
        throw new Error('Usage: node scripts/build-gallery-admin-catalog.mjs [--check]');
    }
    if (argumentsAfterScript.filter(argument => argument === '--check').length > 1) {
        throw new Error('--check may be supplied only once.');
    }

    const check = argumentsAfterScript.includes('--check');
    await writeGalleryAdminCatalog({ check });
    console.log(check
        ? 'Gallery admin catalog snapshot is current.'
        : `Generated ${outputRelativePath}.`
    );
}

const invokedPath = process.argv[1]
    ? fileURLToPath(pathToFileURL(path.resolve(process.argv[1])))
    : '';

if (invokedPath && path.resolve(invokedPath) === path.resolve(fileURLToPath(import.meta.url))) {
    try {
        await runCli();
    } catch (error) {
        console.error(`Gallery admin catalog generation failed: ${error.message}`);
        process.exitCode = 1;
    }
}
